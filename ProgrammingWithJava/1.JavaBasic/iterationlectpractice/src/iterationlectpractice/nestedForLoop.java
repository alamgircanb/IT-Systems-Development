public class nestedForLoop {

    public static void main(String[] args) {
        for (int min = 0; min <= 1; min++) {

            for (int sec = 0; sec <= 2; sec++) {
                System.out.println(min + "m" + sec + "Sec");

            }
            System.out.println("--------minute" + min + "Done------");
        }

    }
}
